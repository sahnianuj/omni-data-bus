#!/usr/bin/env python3
"""Generate and check THIRD_PARTY_NOTICES.md and the dependency licence policy (OC-189).

    python3 scripts/third-party-notices.py            # regenerate (make notices)
    python3 scripts/third-party-notices.py --check    # offline: fail when stale or a licence isn't allowed

What we ship and so must attribute:
  - the Go modules compiled into odb (the server and the runner are the same binary), on every OS we
    release for (linux, darwin, windows), read from the module cache (`go mod download` first);
  - the npm packages bundled into the web app (web/package.json "dependencies", transitively), read
    from web/node_modules (`npm ci` first).
Each is listed with its version, licence and project, followed by the licence texts (MIT and BSD ask
for them to travel with binaries). The licence must be allowed by scripts/licence-policy.json.

LICENSE, NOTICE and THIRD_PARTY_NOTICES.md are also copied where builds need them: the server embeds
them (backend/internal/legal, for exports and /licenses.txt) and the Helm chart ships LICENSE. --check
fails when a copy differs.

As capellactl's scripts/third-party-notices.py (CAP-044), adapted to Go modules and npm packages.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
POLICY = ROOT / "scripts" / "licence-policy.json"
COPIES = {
    ROOT / "LICENSE": [ROOT / "backend/internal/legal/LICENSE", ROOT / "deploy/helm/omni-data-bus/LICENSE"],
    ROOT / "NOTICE": [ROOT / "backend/internal/legal/NOTICE"],
    NOTICES: [ROOT / "backend/internal/legal/THIRD_PARTY_NOTICES.md"],
}
GOOSES = ["linux", "darwin", "windows"]
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING)([.-].*)?$", re.I)

HEADER = """# Third-party notices

Omni-Data-Bus (Apache-2.0, see LICENSE and NOTICE) includes the open-source packages below, which are
distributed under their own licences. Generated by `scripts/third-party-notices.py` (`make notices`); do not
edit by hand. Their licence texts follow the tables.
"""


@dataclass
class Dep:
    name: str
    version: str
    licence: str
    url: str
    texts: list[str] = field(default_factory=list)


def classify(text: str) -> str:
    """SPDX id of a licence file's text ("UNKNOWN" when not recognised)."""
    t = " ".join(text.split())
    found = []
    if "Apache License" in t and "Version 2.0" in t:
        found.append("Apache-2.0")
    if "Permission is hereby granted, free of charge" in t:
        found.append("MIT")
    if "Redistribution and use in source and binary forms" in t:
        found.append("BSD-3-Clause" if ("Neither the name" in t or "endorse or promote" in t) else "BSD-2-Clause")
    if "Permission to use, copy, modify, and/or distribute this software for any purpose" in t:
        found.append("ISC")
    if "Mozilla Public License" in t and ("Version 2.0" in t or "version 2.0" in t):
        found.append("MPL-2.0")
    if "GNU AFFERO GENERAL PUBLIC LICENSE" in t:
        found.append("AGPL-3.0")
    elif "GNU LESSER GENERAL PUBLIC LICENSE" in t:
        found.append("LGPL")
    elif "GNU GENERAL PUBLIC LICENSE" in t:
        found.append("GPL")
    if "SIL OPEN FONT LICENSE" in t.upper():
        found.append("OFL-1.1")
    if not found:
        return "UNKNOWN"
    return " AND ".join(sorted(set(found)))


def licence_files(d: Path) -> list[Path]:
    if not d.is_dir():
        return []
    return sorted((p for p in d.iterdir() if p.is_file() and LICENCE_FILE.match(p.name)), key=lambda p: (len(p.name), p.name))


def go_deps() -> list[Dep]:
    seen: dict[str, Dep] = {}
    for goos in GOOSES:
        env = {**os.environ, "CGO_ENABLED": "0", "GOOS": goos, "GOARCH": "amd64", "GOFLAGS": "-mod=readonly"}
        out = subprocess.run(
            ["go", "list", "-deps", "-f", "{{if not .Standard}}{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}", "./cmd/odb"],
            cwd=ROOT / "backend", env=env, check=True, capture_output=True, text=True,
        ).stdout
        for line in out.splitlines():
            path, version, d = (line.split("\t") + ["", "", ""])[:3]
            if not path or path == "omnidatabus" or path in seen:
                continue
            files = licence_files(Path(d))
            texts = [f.read_text(errors="replace") for f in files[:1]]
            licence = classify(texts[0]) if texts else "UNKNOWN"
            parts = path.split("/")
            url = f"https://github.com/{parts[1]}/{parts[2]}" if parts[0] == "github.com" and len(parts) > 2 else f"https://pkg.go.dev/{path}"
            seen[path] = Dep(path, version, licence, url, texts)
    return sorted(seen.values(), key=lambda d: d.name)


def resolve(name: str, start: Path, top: Path) -> Path | None:
    """node's resolution: name under start's node_modules, then each parent's, up to top."""
    d = start
    while True:
        cand = d / "node_modules" / name
        if (cand / "package.json").is_file():
            return cand
        if d == top or d.parent == d:
            return None
        d = d.parent


def npm_url(pkg: dict) -> str:
    repo = pkg.get("repository")
    if isinstance(repo, dict):
        repo = repo.get("url")
    if isinstance(repo, str) and repo:
        u = re.sub(r"^git\+", "", repo)
        u = re.sub(r"^git://", "https://", u)
        u = re.sub(r"^github:", "https://github.com/", u)
        if re.match(r"^[\w.-]+/[\w.-]+$", u):
            u = "https://github.com/" + u
        return re.sub(r"\.git$", "", u)
    return pkg.get("homepage") or f"https://www.npmjs.com/package/{pkg['name']}"


def npm_licence(pkg: dict) -> str:
    lic = pkg.get("license") or pkg.get("licenses")
    if isinstance(lic, dict):
        lic = lic.get("type")
    if isinstance(lic, list):
        lic = " OR ".join(x.get("type", "UNKNOWN") if isinstance(x, dict) else str(x) for x in lic)
    return str(lic).strip("()") if lic else "UNKNOWN"


def npm_deps() -> list[Dep]:
    web = ROOT / "web"
    if not (web / "node_modules").is_dir():
        sys.exit("web/node_modules is missing: run `npm ci` in web/ first")
    root_pkg = json.loads((web / "package.json").read_text())
    seen: dict[str, Dep] = {}
    todo = [(n, web) for n in sorted(root_pkg.get("dependencies", {}))]
    while todo:
        name, parent = todo.pop()
        d = resolve(name, parent, web)
        if d is None:
            continue
        pkg = json.loads((d / "package.json").read_text())
        key = f"{pkg['name']}@{pkg.get('version', '')}"
        if key in seen:
            continue
        files = licence_files(d)
        texts = [f.read_text(errors="replace") for f in files[:1]]
        seen[key] = Dep(pkg["name"], pkg.get("version", ""), npm_licence(pkg), npm_url(pkg), texts)
        todo.extend((n, d) for n in sorted(pkg.get("dependencies", {})))
    return sorted(seen.values(), key=lambda d: (d.name, d.version))


def allowed(licence: str, name: str, policy: dict) -> bool:
    """SPDX expression check: OR — either side; AND — both; WITH — the base licence."""
    expr = licence.replace("(", " ").replace(")", " ")
    def one(lic: str) -> bool:
        lic = lic.split(" WITH ")[0].strip()
        if lic in policy["allowed"]:
            return True
        return any(name.startswith(p) for p in policy.get("only", {}).get(lic, []))
    return any(all(one(a) for a in alt.split(" AND ")) for alt in expr.split(" OR "))


def render(go: list[Dep], npm: list[Dep]) -> str:
    out = [HEADER]
    out.append("\n## Go modules (compiled into odb and the server)\n\n| Module | Version | Licence | Project |\n|---|---|---|---|\n")
    out += [f"| {d.name} | {d.version} | {d.licence} | {d.url} |\n" for d in go]
    out.append("\n## npm packages (bundled into the web app)\n\n| Package | Version | Licence | Project |\n|---|---|---|---|\n")
    out += [f"| {d.name} | {d.version} | {d.licence} | {d.url} |\n" for d in npm]
    out.append("\n## Licence texts\n")
    groups: dict[str, list[str]] = {}
    for d in go + npm:
        text = d.texts[0].strip() if d.texts else ""
        groups.setdefault(text, []).append(f"{d.name} {d.version}")
    for text, names in groups.items():
        out.append(f"\n### {', '.join(names)}\n\n")
        if text:
            out.append("```text\n" + text.replace("```", "'''") + "\n```\n")
        else:
            out.append("(The package has no licence file; its declared licence is in the table above.)\n")
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail when THIRD_PARTY_NOTICES.md or a copy is stale, or a licence isn't allowed")
    args = ap.parse_args()
    policy = json.loads(POLICY.read_text())
    go, npm = go_deps(), npm_deps()
    bad = [f"{d.name} {d.version}: {d.licence}" for d in go + npm if not allowed(d.licence, d.name, policy)]
    text = render(go, npm)
    problems = []
    if bad:
        problems.append("licences not allowed by scripts/licence-policy.json:\n  " + "\n  ".join(bad))
    if args.check:
        if not NOTICES.exists() or NOTICES.read_text() != text:
            problems.append("THIRD_PARTY_NOTICES.md is stale: run `make notices` and commit it")
        for src, dsts in COPIES.items():
            for dst in dsts:
                if not dst.exists() or dst.read_bytes() != src.read_bytes():
                    problems.append(f"{dst.relative_to(ROOT)} differs from {src.relative_to(ROOT)}: run `make notices`")
    else:
        NOTICES.write_text(text)
        for src, dsts in COPIES.items():
            for dst in dsts:
                dst.parent.mkdir(parents=True, exist_ok=True)
                dst.write_bytes(src.read_bytes())
        print(f"wrote THIRD_PARTY_NOTICES.md: {len(go)} Go modules, {len(npm)} npm packages")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    if args.check:
        print(f"THIRD_PARTY_NOTICES.md is current: {len(go)} Go modules, {len(npm)} npm packages, all licences allowed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
