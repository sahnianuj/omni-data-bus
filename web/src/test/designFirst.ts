// Design-first fixtures (OC-162 – OC-170), generated by the backend (TestPropose_WebFixture):
// the pos source as discovery returns it, the cart design, and its proposal.

export const posSnapshot = snapshot as unknown as Snapshot
export const cartDesign = design as unknown as DocSchema
export const cartProposal = proposal as unknown as Proposal

const tables = (): SourceTable[] => posSnapshot.schemas[0]!.tables

/** A table's hops from its foreign keys, both ways (mirrors relations.Build). */
export function posHops(name: string): RelationHop[] {
  const ref = (n: string) => ({ schema: 'pos', name: n })
  const out: RelationHop[] = []
  for (const t of tables()) {
    for (const fk of t.foreignKeys ?? []) {
      const unique = (t.primaryKey ?? []).join(',') === fk.columns.join(',')
      if (t.name === name) out.push({ from: ref(t.name), to: ref(fk.refTable), kind: 'many-to-one', join: fk.columns.map((c, i) => ({ parent: c, child: fk.refColumns[i]! })), indexed: true, direction: 'references', cardinality: unique ? 'one-to-one' : 'many-to-one' } as RelationHop)
      if (fk.refTable === name) out.push({ from: ref(name), to: ref(t.name), kind: unique ? 'many-to-one' : 'one-to-many', join: fk.refColumns.map((c, i) => ({ parent: c, child: fk.columns[i]! })), indexed: true, direction: 'referencedBy', cardinality: unique ? 'one-to-one' : 'one-to-many' } as RelationHop)
    }
  }
  return out
}

/** A composed mapping of pos.carts holding the cart design, nothing bound. */
export function cartView(over: Partial<MappingView> = {}): MappingView {
  const spec: MappingSpec = {
    specVersion: 2, mode: 'composed', root: { table: { schema: 'pos', name: 'carts' } }, docSchema: cartDesign,
    key: { template: '' }, typeField: { enabled: false, name: '', value: '' }, nullHandling: 'include', relations: [], fieldMappings: [], ignoredColumns: [],
  } as unknown as MappingSpec
  return mappingView({ sourceSchema: 'pos', sourceTable: 'carts', spec, embedCandidates: [], embedTables: {}, issues: [], ...over })
}

/** Serves the pos source, its hops and the proposal (recording proposal requests). */
export function mockPOS(opts: { proposal?: Proposal } = {}) {
  mockSchema(posSnapshot)
  const proposals: unknown[] = []
  server.use(
    http.get('*/api/v1/connections/:id/schema/:schema/:table', ({ params }) => {
      const t = tables().find((x) => x.name === params.table)
      return t ? HttpResponse.json(t) : HttpResponse.json({ status: 404, code: 'NOT_FOUND', title: 'Not found' }, { status: 404 })
    }),
    http.get('*/api/v1/connections/:id/relations/hops', ({ request }) => {
      const [schema = '', name = ''] = (new URL(request.url).searchParams.get('table') ?? '').split('.')
      return HttpResponse.json({ table: { schema, name }, hops: posHops(name), junctions: [], advice: [], maxRelationDepth: 4 })
    }),
    http.get('*/api/v1/connections/:id/relations', ({ request }) => {
      const [schema = '', name = ''] = (new URL(request.url).searchParams.get('root') ?? '').split('.')
      return HttpResponse.json({ root: { schema, name }, depth: 4, paths: posHops(name).map((h) => ({ hops: [h] })), junctions: [], advice: [] })
    }),
    http.post('*/api/v1/projects/:pid/mappings/:mid/propose', async ({ request }) => {
      proposals.push(await request.json())
      return HttpResponse.json(opts.proposal ?? cartProposal)
    }),
    http.post('*/api/v1/projects/:pid/mappings/:mid/preview', () => HttpResponse.json({ writeMode: 'upsert', items: [], summary: { ok: 0, errors: 0, avgSizeBytes: 0, maxSizeBytes: 0, collisions: 0 } })),
  )
  return { proposals }
}

/** The cart mapping, open in the composer (returns mockMapping's state). */
export function openCart(over: Partial<MappingView> = {}) {
  return mockMapping(cartView(over))
}
